/* Helper: Search and Match Food by Name or Keywords (RESTAURANT MODE ONLY) */
function matchFoodCatalogItem(query, shopType) {
  // If active shop is not a restaurant, strictly do not match restaurant food items or food photos
  const effectiveShop = shopType || (typeof currentShopType !== 'undefined' ? currentShopType : 'restaurant');
  if (effectiveShop !== 'restaurant') return null;

  if (!query || typeof query !== 'string') return null;
  const qClean = query.toLowerCase().trim().replace(/[^a-z0-9\s]/g, ' ');
  const tokens = qClean.split(/\s+/).filter(w => w.length >= 2);
  if (!tokens.length) return null;

  let bestMatch = null;
  let highestScore = 0;

  for (const item of FOOD_CATALOG) {
    let score = 0;
    const nameLower = item.name.toLowerCase();

    // Direct substring in canonical name
    if (nameLower.includes(qClean)) {
      score += 60;
    }

    // Keyword matches
    for (const kw of item.keywords) {
      if (kw === qClean) {
        score += 80;
      } else if (qClean.includes(kw)) {
        score += 50;
      } else if (kw.includes(qClean)) {
        score += 40;
      }

      // Token-level matching
      for (const t of tokens) {
        if (kw === t) {
          score += 35;
        } else if (kw.includes(t)) {
          score += 20;
        }
      }
    }

    // Levenshtein / fuzzy check for common typos (e.g. parata vs paratha)
    for (const kw of item.keywords) {
      for (const t of tokens) {
        if (Math.abs(kw.length - t.length) <= 2) {
          const dist = levenshteinDistance(kw, t);
          if (dist === 1) score += 30;
          else if (dist === 2 && t.length >= 5) score += 15;
        }
      }
    }

    if (score > highestScore) {
      highestScore = score;
      bestMatch = { ...item, score };
    }
  }

  // Minimum threshold to prevent false positives
  return highestScore >= 18 ? bestMatch : null;
}

function levenshteinDistance(a, b) {
  const m = a.length, n = b.length;
  const dp = Array.from({ length: m + 1 }, () => new Array(n + 1).fill(0));
  for (let i = 0; i <= m; i++) dp[i][0] = i;
  for (let j = 0; j <= n; j++) dp[0][j] = j;

  for (let i = 1; i <= m; i++) {
    for (let j = 1; j <= n; j++) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      dp[i][j] = Math.min(
        dp[i - 1][j] + 1,
        dp[i][j - 1] + 1,
        dp[i - 1][j - 1] + cost
      );
    }
  }
  return dp[m][n];
}

